import 'package:flutter/material.dart';

String tr(BuildContext context, String english) => Localizations.localeOf(context).languageCode == 'fa' ? (persianText[english] ?? english) : english;

class LText extends StatelessWidget {
  final String text;
  final TextStyle? style;
  final TextOverflow? overflow;
  const LText(this.text, {super.key, this.style, this.overflow});
  @override
  Widget build(BuildContext context) => Text(tr(context, text), style: style, overflow: overflow);
}

String uiNumber(BuildContext context, int value) {
  final original = value.toString();
  if (Localizations.localeOf(context).languageCode != 'fa') return original;
  const digits = '۰۱۲۳۴۵۶۷۸۹';
  return original.replaceAllMapped(RegExp(r'[0-9]'), (match) => digits[int.parse(match[0]!)]);
}

